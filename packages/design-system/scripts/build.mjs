#!/usr/bin/env node
// Generates dist/ from src/tokens.source.json and brand/ (no dependencies).
//   node scripts/build.mjs          write dist/
//   node scripts/build.mjs --check  exit 1 when dist/ is stale (CI runs this)
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const HEADER = '/* GENERATED by scripts/build.mjs from src/tokens.source.json. Do not edit; edit the source. */';

export function loadSource(path = join(ROOT, 'src/tokens.source.json')) {
  const src = JSON.parse(readFileSync(path, 'utf8'));
  for (const [name, t] of Object.entries(src.tokens)) {
    const kinds = ['value' in t, 'alias' in t, 'light' in t || 'dark' in t].filter(Boolean).length;
    if (kinds !== 1) throw new Error(`token ${name}: exactly one of value / alias / light+dark`);
    if (!('value' in t) && !('alias' in t) && !src.themes.every((th) => th in t)) throw new Error(`token ${name}: needs a value for every theme`);
    if ('alias' in t && !(t.alias in src.tokens)) throw new Error(`token ${name}: alias to unknown ${t.alias}`);
    if (!t.from) throw new Error(`token ${name}: missing \`from\` (provenance)`);
  }
  for (const p of src.pluginTokens) if (!(p in src.tokens)) throw new Error(`pluginTokens: unknown ${p}`);
  return src;
}

const isTheme = (t) => !('value' in t);

/** Theme-dependent tokens as CSS text for one theme (aliases stay var() so they track the theme block). */
function themeDecls(src, theme) {
  return Object.entries(src.tokens).filter(([, t]) => isTheme(t))
    .map(([n, t]) => `  --${n}: ${'alias' in t ? `var(--${t.alias})` : t[theme]};`).join('\n');
}

export function buildCss(src) {
  const scale = Object.entries(src.tokens).filter(([, t]) => !isTheme(t)).map(([n, t]) => `  --${n}: ${t.value};`).join('\n');
  const light = themeDecls(src, 'light');
  const dark = themeDecls(src, 'dark');
  const indent = (s) => s.replace(/^/gm, '  ');
  // Dark is the default ground (the family's graphite). With no data-theme the OS preference
  // picks; data-theme="light|dark" (or studio's wicked-light|wicked-dark) pins it, on the root or
  // on any subtree. Everything sits in one cascade layer so a consumer's unlayered rules win.
  return `${HEADER}
@layer wicked-design {
:root {
${scale}
}
:root,
[data-theme="dark"],
[data-theme="wicked-dark"] {
  color-scheme: dark;
${dark}
}
@media (prefers-color-scheme: light) {
  :root:not([data-theme]) {
    color-scheme: light;
${indent(light)}
  }
}
[data-theme="light"],
[data-theme="wicked-light"] {
  color-scheme: light;
${light}
}
}
`;
}

/** A token's concrete value in a theme: aliases followed, var(--x) substituted. */
export function resolve(src, name, theme, seen = new Set()) {
  if (seen.has(name)) throw new Error(`alias cycle at ${name}`);
  seen.add(name);
  const t = src.tokens[name];
  if (!t) throw new Error(`unknown token ${name}`);
  const raw = 'alias' in t ? resolve(src, t.alias, theme, seen) : 'value' in t ? t.value : t[theme];
  return raw.replace(/var\(--([a-z0-9-]+)\)/g, (_, ref) => resolve(src, ref, theme, new Set(seen)));
}

export function buildJson(src, version) {
  const themes = {};
  for (const th of src.themes) {
    themes[th] = {};
    for (const [n, t] of Object.entries(src.tokens)) if (isTheme(t)) themes[th][n] = resolve(src, n, th);
  }
  const scale = {};
  for (const [n, t] of Object.entries(src.tokens)) if (!isTheme(t)) scale[n] = t.value;
  const aliases = Object.fromEntries(Object.entries(src.tokens).filter(([, t]) => 'alias' in t).map(([n, t]) => [n, t.alias]));
  const tokens = Object.fromEntries(Object.entries(src.tokens).map(([n, t]) => [n, { group: t.group, from: t.from, ...(t.note ? { note: t.note } : {}) }]));
  return JSON.stringify({
    $comment: 'GENERATED by scripts/build.mjs from src/tokens.source.json. Values are resolved (no var()). CSS consumers use dist/tokens.css.',
    name: src.name, version, themes, scale, aliases, pluginTokens: src.pluginTokens, groups: src.groups, tokens,
  }, null, 2) + '\n';
}

/** The lockup with the token references replaced by one theme's values, for <img>/favicon use. */
export function lockupFor(src, svg, theme) {
  return svg.replace(/var\(--([a-z0-9-]+)\)/g, (_, n) => resolve(src, n, theme));
}

/** The icon sheet split into one file per icon, drawn in currentColor. */
export function splitIcons(sheet) {
  const out = {};
  for (const m of sheet.matchAll(/<g id="icon-([a-z0-9-]+)">\s*<svg[^>]*>([\s\S]*?)<\/svg>\s*<\/g>/g)) {
    const body = m[2].replace(/#111111/g, 'currentColor').replace(/^\s+/gm, '  ').trim();
    out[m[1]] = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 160 160" fill="none">\n  ${body}\n</svg>\n`;
  }
  return out;
}

