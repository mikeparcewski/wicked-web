export function buildAll() {
  const src = loadSource();
  const { version } = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
  const files = { 'dist/tokens.css': buildCss(src), 'dist/tokens.json': buildJson(src, version) };
  const lockup = readFileSync(join(ROOT, 'brand/wicked-agile-lockup.svg'), 'utf8');
  for (const th of src.themes) files[`dist/brand/wicked-agile-lockup.${th}.svg`] = lockupFor(src, lockup, th);
  const icons = splitIcons(readFileSync(join(ROOT, 'brand/wicked-agile-icons.svg'), 'utf8'));
  for (const [n, svg] of Object.entries(icons)) files[`dist/icons/${n}.svg`] = svg;
  files['dist/specimen.html'] = buildSpecimen(src, lockup, icons);
  return files;
}

const listDist = (dir = join(ROOT, 'dist'), rel = 'dist') => existsSync(dir)
  ? readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? listDist(join(dir, e.name), `${rel}/${e.name}`) : [`${rel}/${e.name}`]))
  : [];

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const files = buildAll();
  if (process.argv.includes('--check')) {
    const stale = Object.entries(files).filter(([p, c]) => !existsSync(join(ROOT, p)) || readFileSync(join(ROOT, p), 'utf8') !== c).map(([p]) => p);
    const extra = listDist().filter((p) => !(p in files));
    if (stale.length || extra.length) {
      console.error(`dist/ is out of date. Run \`npm run build\`.\n stale: ${stale.join(', ') || '-'}\n extra: ${extra.join(', ') || '-'}`);
      process.exit(1);
    }
    console.log(`dist/ up to date (${Object.keys(files).length} files)`);
  } else {
    for (const [p, c] of Object.entries(files)) { mkdirSync(dirname(join(ROOT, p)), { recursive: true }); writeFileSync(join(ROOT, p), c); }
    console.log(`wrote ${Object.keys(files).length} files`);
  }
}
